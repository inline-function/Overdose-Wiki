export type TextParams = Record<string, string | number>;

function interpolate(text: string, params?: TextParams): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match,
  );
}

/** Translate one of engine.ts's Chinese strings. In zh the key itself is the
 *  output, so the Chinese build stays byte-identical. */
export function z(zh: string, params?: TextParams): string {
  const text = getLocale() === 'en' ? (EN[zh] ?? zh) : zh;
  return interpolate(text, params);
}

export function joinList(items: string[]): string {
  return items.join(getLocale() === 'en' ? '; ' : '；');
}

export function hasTranslation(zh: string): boolean {
  return Object.prototype.hasOwnProperty.call(EN, zh);
}